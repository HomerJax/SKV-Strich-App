-- strikr: Kabinen-Talk comments, attendance review and non-monetary fun wheel.
create table if not exists public.team_feed_comments (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.clubs(id) on delete cascade,
  feed_id text not null check (char_length(feed_id) between 3 and 160),
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint team_feed_comments_one_per_user unique (club_id,feed_id,user_id)
);
create index if not exists team_feed_comments_feed_lookup on public.team_feed_comments(club_id,feed_id,created_at);
alter table public.team_feed_comments enable row level security;
create policy "team_feed_comments_read_club" on public.team_feed_comments
for select to authenticated using (public.is_member_of_club(club_id));
-- Mutations are server-mediated after feed validation and per-user authorization.

create table if not exists public.session_attendance_reviews (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.clubs(id) on delete cascade,
  session_id bigint not null references public.sessions(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  kind text not null check (kind in ('late_cancel','no_show')),
  status text not null default 'pending' check (status in ('pending','penalized','excused')),
  note text not null default '' check (char_length(note) <= 500),
  reported_by uuid references auth.users(id) on delete set null,
  reported_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  penalty_id bigint references public.penalties(id) on delete set null,
  unique (session_id,player_id)
);
create index if not exists attendance_review_club_session on public.session_attendance_reviews (club_id,session_id,status);
alter table public.session_attendance_reviews enable row level security;
create policy "attendance_reviews_read_club" on public.session_attendance_reviews
for select to authenticated using (public.is_member_of_club(club_id));
-- Writes only through server routes with role checking.

create table if not exists public.penalty_wheel_spins (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.clubs(id) on delete cascade,
  penalty_id bigint not null references public.penalties(id) on delete cascade unique,
  player_id bigint not null references public.players(id) on delete cascade,
  outcome text not null check (outcome in ('lucky','usual','confession','challenge')),
  spun_by uuid not null references auth.users(id),
  spun_at timestamptz not null default now()
);
create index if not exists penalty_wheel_club on public.penalty_wheel_spins(club_id,player_id);
alter table public.penalty_wheel_spins enable row level security;
create policy "penalty_wheel_read_club" on public.penalty_wheel_spins
for select to authenticated using (public.is_member_of_club(club_id));

