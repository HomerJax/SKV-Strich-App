create policy "work_duty_signups_insert_own"
on public.work_duty_signups for insert
with check (
  exists (
    select 1
    from public.players p
    join public.club_memberships cm
      on cm.club_id = p.club_id
     and cm.user_id = auth.uid()
    where p.id = work_duty_signups.player_id
      and p.club_id = work_duty_signups.club_id
      and p.user_id = auth.uid()
  )
);

