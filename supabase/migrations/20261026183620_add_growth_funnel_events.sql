create table if not exists public.growth_funnel_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in (
    'registration_completed',
    'club_created',
    'first_training_created',
    'first_training_completed'
  )),
  club_id uuid references public.clubs(id) on delete cascade,
  occurred_at timestamptz not null default now(),
  constraint growth_funnel_club_required check (
    (event_name = 'registration_completed' and club_id is null)
    or (event_name <> 'registration_completed' and club_id is not null)
  )
);

create unique index if not exists growth_funnel_one_club_milestone
  on public.growth_funnel_events (event_name, club_id)
  where club_id is not null;

create index if not exists growth_funnel_events_occurred_at_idx
  on public.growth_funnel_events (occurred_at desc);

alter table public.growth_funnel_events enable row level security;
revoke all on public.growth_funnel_events from anon, authenticated;
grant all on public.growth_funnel_events to service_role;
grant usage, select on sequence public.growth_funnel_events_id_seq to service_role;

comment on table public.growth_funnel_events is
  'Minimal server-written conversion milestones; no visitor IDs, names, or email addresses.';
